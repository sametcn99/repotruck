import { afterAll, beforeAll, describe, expect, test } from "bun:test";
import { mkdirSync, mkdtempSync, readFileSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { CUSTOM_INSTRUCTIONS_BEGIN, CUSTOM_INSTRUCTIONS_END } from "../src/services/agentsMd.ts";
import { GUIDE_BEGIN, GUIDE_VERSION, parseGuideVersion } from "../src/services/agentsMdGuide.ts";
import { migrateAgentsMdGuides } from "../src/services/agentsMdMigration.ts";
import type { RepotruckConfig } from "../src/services/config.ts";
import { AGENTS_MD_FILENAME, readAgentsMd } from "../src/services/config.ts";
import { updateWorkspace } from "../src/services/workspace.ts";

const tempRoots: string[] = [];
let savedConfigDir: string | undefined;
let env: Record<string, string | undefined>;
let wsRoot: string;

function tempDir(prefix: string): string {
  const dir = (realpathSync.native ?? realpathSync)(mkdtempSync(path.join(tmpdir(), prefix)));
  tempRoots.push(dir);
  return dir;
}

/** An AGENTS.md as written by repotruck before the guide section existed. */
function legacyAgentsMd(customText: string): string {
  return [
    "<!-- AUTO-GENERATED by repotruck. Do not edit by hand; this file is rewritten on every sync or clone. -->",
    "",
    "# Repository Workspace Map",
    "",
    "## Workspace Metadata",
    "",
    "- Preset: `categorized`",
    "- Last sync: 2026-10-23T10:00:00.000Z",
    "- Total repositories: 1 (1 internal, 0 community)",
    "",
    "## Internal Projects",
    "",
    "- `acme/api` — `acme/source/api` (TypeScript)",
    "",
    "## Agent Rules",
    "",
    "- Each directory is an independent Git project.",
    "",
    "## Custom Instructions",
    "",
    CUSTOM_INSTRUCTIONS_BEGIN,
    customText,
    CUSTOM_INSTRUCTIONS_END,
    "",
  ].join("\n");
}

beforeAll(async () => {
  savedConfigDir = process.env.REPOTRUCK_CONFIG_DIR;
  const configDir = tempDir("repotruck-agentsmd-mig-cfg-");
  process.env.REPOTRUCK_CONFIG_DIR = configDir;
  env = { REPOTRUCK_CONFIG_DIR: configDir };

  wsRoot = tempDir("repotruck-agentsmd-mig-ws-");
  mkdirSync(path.join(wsRoot, "acme", "source", "api"), { recursive: true });
  const config: RepotruckConfig = {
    version: 1,
    root: wsRoot,
    preset: "categorized",
    lastSync: "2026-10-23T10:00:00.000Z",
    repos: [
      {
        owner: "acme",
        name: "api",
        relativePath: "acme/source/api",
        internal: true,
        category: "source",
        language: "TypeScript",
        updatedAt: null,
      },
    ],
  };
  await updateWorkspace(wsRoot, () => ({ config, result: undefined }));
});

afterAll(() => {
  if (savedConfigDir === undefined) {
    delete process.env.REPOTRUCK_CONFIG_DIR;
  } else {
    process.env.REPOTRUCK_CONFIG_DIR = savedConfigDir;
  }
  for (const dir of tempRoots) {
    rmSync(dir, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 });
  }
});

describe("migrateAgentsMdGuides", () => {
  test("upgrades a legacy AGENTS.md and preserves custom instructions", async () => {
    const custom = ["# My rules", "- answer in Turkish"].join("\n");
    writeFileSync(path.join(wsRoot, AGENTS_MD_FILENAME), legacyAgentsMd(custom), "utf8");
    expect(parseGuideVersion(readFileSync(path.join(wsRoot, AGENTS_MD_FILENAME), "utf8"))).toBe(0);

    const result = await migrateAgentsMdGuides(env);
    expect(result.migrated).toBe(1);
    expect(result.failed).toBe(0);

    const upgraded = await readAgentsMd(wsRoot);
    expect(upgraded).not.toBeNull();
    expect(parseGuideVersion(upgraded!)).toBe(GUIDE_VERSION);
    expect(upgraded).toContain(GUIDE_BEGIN);
    expect(upgraded).toContain("## Working with repotruck");
    expect(upgraded).toContain("repotruck_sync");
    // the map itself survived the rewrite
    expect(upgraded).toContain("- `acme/api` — `acme/source/api` (TypeScript)");
    // the user's own instructions survived verbatim
    expect(upgraded).toContain(CUSTOM_INSTRUCTIONS_BEGIN);
    expect(upgraded).toContain("# My rules\n- answer in Turkish");
    expect(upgraded).toContain(CUSTOM_INSTRUCTIONS_END);
  });

  test("is a no-op when the guide is already current", async () => {
    const before = await readAgentsMd(wsRoot);
    const result = await migrateAgentsMdGuides(env);
    expect(result.migrated).toBe(0);
    expect(result.failed).toBe(0);
    expect(await readAgentsMd(wsRoot)).toBe(before);
  });

  test("skips workspaces whose directory is gone without recreating it", async () => {
    const goneRoot = tempDir("repotruck-agentsmd-mig-gone-");
    const config: RepotruckConfig = {
      version: 1,
      root: goneRoot,
      preset: "categorized",
      lastSync: null,
      repos: [],
    };
    await updateWorkspace(goneRoot, () => ({ config, result: undefined }));
    // remove the directory after registration, as if the user deleted it
    rmSync(goneRoot, { recursive: true, force: true });

    const result = await migrateAgentsMdGuides(env);
    expect(result.failed).toBe(0);
    // directory must not be resurrected by the migration
    const restored = await readAgentsMd(goneRoot);
    expect(restored).toBeNull();
  });
});
