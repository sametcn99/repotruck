import path from "node:path";
import { type GenerateAgentsMdInput, generateAgentsMd } from "./agentsMd.ts";
import { writeFileAtomic } from "./fsUtils.ts";

export type InstructionFormat = "agents" | "cursor" | "claude" | "copilot";

export const INSTRUCTION_FORMATS: readonly InstructionFormat[] = [
  "agents",
  "cursor",
  "claude",
  "copilot",
];

export function isInstructionFormat(val: string): val is InstructionFormat {
  return (INSTRUCTION_FORMATS as readonly string[]).includes(val);
}

export function defaultOutputPathForFormat(root: string, format: InstructionFormat): string {
  switch (format) {
    case "agents":
      return path.join(root, "AGENTS.md");
    case "cursor":
      return path.join(root, ".cursorrules");
    case "claude":
      return path.join(root, "CLAUDE.md");
    case "copilot":
      return path.join(root, ".github", "copilot-instructions.md");
  }
}

export function formatInstructions(
  input: GenerateAgentsMdInput,
  format: InstructionFormat,
): string {
  const baseMarkdown = generateAgentsMd(input);

  switch (format) {
    case "agents":
      return baseMarkdown;

    case "cursor": {
      return [
        "---",
        "description: Workspace multi-repository directory map and agent rules",
        "globs: *",
        "alwaysApply: true",
        "---",
        "",
        "# Cursor Rules \u2014 Multi-Repo Workspace",
        "",
        "> This file was generated by repotruck to inform Cursor of the multi-repository workspace layout.",
        "",
        baseMarkdown,
      ].join("\n");
    }

    case "claude": {
      return [
        "# Claude Code Workspace Configuration",
        "",
        "> Automatically generated by repotruck for Claude Code sessions.",
        "",
        "## Multi-Repo Guidance",
        "- This directory is a repotruck multi-repository workspace root.",
        "- Always navigate into the relevant project subfolder before executing git or build commands.",
        "- Do not perform git actions in the workspace root unless using repotruck commands.",
        "",
        baseMarkdown,
      ].join("\n");
    }

    case "copilot": {
      return [
        "# GitHub Copilot Workspace Instructions",
        "",
        "> Generated by repotruck. Informs GitHub Copilot Chat and CLI of workspace layout.",
        "",
        baseMarkdown,
      ].join("\n");
    }
  }
}

export async function exportInstructionsFile(
  root: string,
  input: GenerateAgentsMdInput,
  format: InstructionFormat,
  outPath?: string,
): Promise<{ format: InstructionFormat; targetPath: string }> {
  const targetPath = outPath ?? defaultOutputPathForFormat(root, format);
  const content = formatInstructions(input, format);
  await writeFileAtomic(targetPath, content);
  return { format, targetPath };
}
