/**
 * The CLI + MCP usage guide embedded into every generated AGENTS.md.
 *
 * The guide is a managed section between versioned markers: rewrites
 * regenerate it wholesale (custom instructions stay in their own preserved
 * block), and the launcher migration upgrades older files in registered
 * workspaces as soon as a newer repotruck runs (see agentsMdMigration.ts).
 *
 * Content is built from the same sources as the website docs — the parity
 * registry via registryDocs.ts and the MCP tool catalog — so the guide can
 * never drift from the actual command and tool surface. Bump GUIDE_VERSION
 * whenever the guide layout changes so existing AGENTS.md files refresh.
 */
import { buildCommandGroupsData, DOC_EXAMPLES, type GenCommand } from "../commands/registryDocs.ts";
import { MCP_PROMPT_CATALOG, MCP_TOOL_CATALOG } from "../mcp/toolCatalog.ts";

export const GUIDE_VERSION = 1;

export const GUIDE_BEGIN = `<!-- repotruck:guide begin v${GUIDE_VERSION} (managed section — regenerated by repotruck on every sync; only the Custom Instructions block below survives rewrites) -->`;
export const GUIDE_END = "<!-- repotruck:guide end -->";

const GUIDE_VERSION_PATTERN = /<!--\s*repotruck:guide begin v(\d+)\b/;

/** Guide version embedded in an AGENTS.md; 0 when the file predates guides. */
export function parseGuideVersion(content: string): number {
  const match = GUIDE_VERSION_PATTERN.exec(content);
  return match === null ? 0 : Number.parseInt(match[1] ?? "0", 10);
}

function commandLines(command: GenCommand): string[] {
  const lines: string[] = [];
  const usageParts = command.usage.split(" | ");
  lines.push(`- \`${usageParts[0]}\` — ${command.summary}`);
  // Extra usage forms (e.g. `sync resolve`) follow as plain code lines.
  for (const form of usageParts.slice(1)) {
    lines.push(`  \`${form}\``);
  }
  for (const flag of command.flags ?? []) {
    lines.push(`  - \`${flag.flag}\` — ${flag.description}`);
  }
  return lines;
}

function cliReferenceLines(): string[] {
  const { commandGroups, globalFlags } = buildCommandGroupsData();
  const lines: string[] = [
    "### CLI quick reference",
    "",
    "Every command accepts `--json` where noted; run `repotruck <command> --help` for the full flag list.",
  ];
  for (const group of commandGroups) {
    lines.push("", `#### ${group.title}`, "");
    for (const command of group.commands) {
      lines.push(...commandLines(command));
    }
  }
  if (globalFlags.length > 0) {
    lines.push("", "#### Global flags", "");
    for (const flag of globalFlags) {
      lines.push(`- \`${flag.flag}\` — ${flag.description}`);
    }
  }
  return lines;
}

const WORKFLOW_KEYS: readonly { command: string; pick: readonly number[] }[] = [
  { command: "sync", pick: [0, 7] },
  { command: "status", pick: [0, 1] },
  { command: "run", pick: [0, 1] },
  { command: "search-code", pick: [0, 2] },
  { command: "changelog", pick: [0] },
];

function workflowLines(): string[] {
  const lines: string[] = ["### Common workflows", ""];
  for (const { command, pick } of WORKFLOW_KEYS) {
    const examples = DOC_EXAMPLES[command] ?? [];
    for (const index of pick) {
      const example = examples[index];
      if (example !== undefined) lines.push(`- \`${example}\``);
    }
  }
  return lines;
}

function mcpLines(): string[] {
  const lines: string[] = [
    "### MCP tools (for coding agents)",
    "",
    'repotruck ships an MCP server so agents can drive the workspace directly. Register it (Claude Code, Cursor, ...) with command `repotruck` and args `["mcp"]`:',
    "",
    "```json",
    '{ "mcpServers": { "repotruck": { "command": "repotruck", "args": ["mcp"] } } }',
    "```",
    "",
    "Streamable HTTP instead of stdio: `repotruck mcp --http [--port N] [--host H] [--token T]`.",
    "",
  ];
  for (const tool of MCP_TOOL_CATALOG) {
    lines.push(`- \`${tool.name}\` — ${tool.description}`);
  }
  lines.push("", "Prompts:", "");
  for (const prompt of MCP_PROMPT_CATALOG) {
    lines.push(`- \`${prompt.name}\` — ${prompt.description}`);
  }
  return lines;
}

/** The full managed guide section, markers included. */
export function renderAgentsMdGuide(): string {
  const lines: string[] = [
    GUIDE_BEGIN,
    "",
    "## Working with repotruck",
    "",
    "This workspace is managed by [repotruck](https://sametcn99.github.io/repotruck/): it clones and updates the repositories listed above, keeps this map current and exposes both a CLI and an MCP server for working across them. This AGENTS.md is regenerated on every sync — only the Custom Instructions block below survives rewrites, so keep workspace-specific rules there.",
  ];
  lines.push("", ...cliReferenceLines());
  lines.push("", ...workflowLines());
  lines.push("", ...mcpLines());
  lines.push(GUIDE_END);
  return lines.join("\n");
}
